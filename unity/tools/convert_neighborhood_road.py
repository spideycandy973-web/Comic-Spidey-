"""Extract a straight road piece and its colour atlas from the supplied city GLB.

Usage: python unity/tools/convert_neighborhood_road.py /path/to/Untitled.glb
The GLB comes from source/Untitled.glb in neighbourhood-city-modular-lowpoly.zip
in the user's Drive. Source geometry uses Z-up for this mesh; Unity uses Y-up.
The full downloaded archive is deliberately not committed to the repository.
"""
import json
import pathlib
import struct
import sys

root = pathlib.Path(__file__).resolve().parents[2]
data = pathlib.Path(sys.argv[1]).read_bytes()
magic, version, _ = struct.unpack_from('<4sII', data)
if (magic, version) != (b'glTF', 2):
    raise ValueError('Expected a GLB version 2 file')
length, kind = struct.unpack_from('<I4s', data, 12)
if kind != b'JSON':
    raise ValueError('Expected JSON chunk')
model = json.loads(data[20:20 + length])
bin_size, kind = struct.unpack_from('<I4s', data, 20 + length)
if kind != b'BIN\0':
    raise ValueError('Expected binary chunk')
binary = data[28 + length:28 + length + bin_size]
mesh = next(m for m in model['meshes'] if m.get('name') == 'Road_0_Modular_Road_0.001')
primitive = mesh['primitives'][0]


def values(index, code, components):
    accessor = model['accessors'][index]
    view = model['bufferViews'][accessor['bufferView']]
    if accessor['componentType'] != {'f': 5126, 'H': 5123}[code] or view['buffer'] != 0:
        raise ValueError('Unexpected road vertex/index encoding')
    stride = view.get('byteStride', struct.calcsize('<' + code * components))
    start = view.get('byteOffset', 0) + accessor.get('byteOffset', 0)
    return [struct.unpack_from('<' + code * components, binary, start + i * stride)
            for i in range(accessor['count'])]


attributes = primitive['attributes']
positions = values(attributes['POSITION'], 'f', 3)
normals = values(attributes['NORMAL'], 'f', 3)
uvs = values(attributes['TEXCOORD_0'], 'f', 2)
indices = [item[0] for item in values(primitive['indices'], 'H', 1)]
if not (len(positions) == len(normals) == len(uvs) == 138 and len(indices) == 216):
    raise ValueError('Unexpected road geometry')
lines = ['# Supplied neighborhood road; generated by unity/tools/convert_neighborhood_road.py', 'o road_strip']
# Swap Y and Z: this flips handedness, so reverse triangle winding.
lines += [f'v {x:.7g} {z:.7g} {y:.7g}' for x, y, z in positions]
lines += [f'vt {u:.7g} {1-v:.7g}' for u, v in uvs]
lines += [f'vn {x:.7g} {z:.7g} {y:.7g}' for x, y, z in normals]
for i in range(0, len(indices), 3):
    face = [indices[i] + 1, indices[i + 2] + 1, indices[i + 1] + 1]
    if not all(1 <= n <= len(positions) for n in face):
        raise ValueError('Out-of-range triangle')
    lines.append('f ' + ' '.join(f'{n}/{n}/{n}' for n in face))
output = root / 'unity/ComicSpidey/Assets/Resources/City'
output.mkdir(parents=True, exist_ok=True)
(output / 'road_strip.obj').write_text('\n'.join(lines) + '\n')
material = model['materials'][primitive['material']]
texture = model['textures'][material['pbrMetallicRoughness']['baseColorTexture']['index']]
image = model['images'][texture['source']]
if image['mimeType'] != 'image/jpeg':
    raise ValueError('Unexpected road texture format')
view = model['bufferViews'][image['bufferView']]
start = view.get('byteOffset', 0)
(output / 'road_strip.jpg').write_bytes(binary[start:start + view['byteLength']])
print(f'Exported {len(positions)} vertices and {len(indices)//3} triangles plus the base-colour atlas')
