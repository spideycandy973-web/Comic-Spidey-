"""Convert the supplied static GLB street light to Unity's native OBJ format.

This intentionally handles this one known, uncompressed asset only. It flips Z
and triangle winding (glTF to Unity coordinate handedness), flips image V, and
keeps positions, normals and base-colour UVs. Original in godot/assets/city/.
"""
import json
import pathlib
import struct

ROOT = pathlib.Path(__file__).resolve().parents[2]
data = (ROOT / 'godot/assets/city/street-light.glb').read_bytes()
magic, version, _ = struct.unpack_from('<4sII', data)
assert magic == b'glTF' and version == 2
json_length, json_type = struct.unpack_from('<I4s', data, 12)
assert json_type == b'JSON'
model = json.loads(data[20:20 + json_length])
bin_length, bin_type = struct.unpack_from('<I4s', data, 20 + json_length)
assert bin_type == b'BIN\0'
binary = data[28 + json_length:28 + json_length + bin_length]
primitive = model['meshes'][0]['primitives'][0]
assert primitive['mode'] == 4


def values(index, code, components):
    accessor = model['accessors'][index]
    view = model['bufferViews'][accessor['bufferView']]
    stride = view.get('byteStride', struct.calcsize('<' + code * components))
    start = view.get('byteOffset', 0) + accessor.get('byteOffset', 0)
    assert accessor['componentType'] == {'f': 5126, 'H': 5123}[code]
    return [struct.unpack_from('<' + code * components, binary, start + i * stride)
            for i in range(accessor['count'])]


attrs = primitive['attributes']
positions = values(attrs['POSITION'], 'f', 3)
normals = values(attrs['NORMAL'], 'f', 3)
uvs = values(attrs['TEXCOORD_0'], 'f', 2)
indices = [item[0] for item in values(primitive['indices'], 'H', 1)]
assert len(positions) == len(normals) == len(uvs) and len(indices) % 3 == 0
lines = ['# Supplied neighbourhood pack street light; generated by unity/tools/convert_street_light.py', 'o street-light']
lines += [f'v {x:.7g} {y:.7g} {-z:.7g}' for x, y, z in positions]
lines += [f'vt {u:.7g} {1-v:.7g}' for u, v in uvs]
lines += [f'vn {x:.7g} {y:.7g} {-z:.7g}' for x, y, z in normals]
for i in range(0, len(indices), 3):
    face = [indices[i] + 1, indices[i + 2] + 1, indices[i + 1] + 1]
    assert all(1 <= n <= len(positions) for n in face)
    lines.append('f ' + ' '.join(f'{n}/{n}/{n}' for n in face))
out = ROOT / 'unity/ComicSpidey/Assets/Resources/City'
out.mkdir(parents=True, exist_ok=True)
(out / 'street-light.obj').write_text('\n'.join(lines) + '\n')
texture_index = model['materials'][primitive['material']]['pbrMetallicRoughness']['baseColorTexture']['index']
image = model['images'][model['textures'][texture_index]['source']]
assert image['mimeType'] == 'image/png'
view = model['bufferViews'][image['bufferView']]
start = view.get('byteOffset', 0)
(out / 'street-light.png').write_bytes(binary[start:start + view['byteLength']])
print(f'converted {len(positions)} vertices and {len(indices) // 3} triangles')
